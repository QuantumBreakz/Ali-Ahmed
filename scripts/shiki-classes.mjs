// Shiki writes style="--shiki-light:#a0111f;--shiki-dark:#f97583" on every highlighted token, which made code-heavy
// pages mostly markup. This transformer swaps that for two short classes (sl-a0111f sd-f97583); the classes are defined
// in src/styles/shiki-colors.css, generated from both themes by `node scripts/shiki-classes.mjs`.
import { writeFileSync } from "node:fs";
import dark from "@shikijs/themes/github-dark";
import light from "@shikijs/themes/github-light-high-contrast";

export const shikiThemes = { light: "github-light-high-contrast", dark: "github-dark" };
// The themes' comment greys fall below 4.5:1 on our code backgrounds; use darker/lighter greys that pass.
export const colorReplacements = { "github-light-high-contrast": { "#66707b": "#57606a" }, "github-dark": { "#6a737d": "#a0a8b2" } };

const palette = (theme) => {
  const swap = colorReplacements[theme.name] ?? {};
  const colors = [theme.fg, ...Object.values(theme.colors ?? {}), ...(theme.tokenColors ?? []).map((t) => t.settings?.foreground)]
    .filter((c) => typeof c === "string" && /^#[0-9a-f]{3,8}$/i.test(c))
    .map((c) => (swap[c.toLowerCase()] ?? c).toLowerCase());
  return new Set(colors);
};
const known = { sl: palette(light), sd: palette(dark) };

const STYLE = /^--shiki-light:(#[0-9a-fA-F]{3,8});--shiki-dark:(#[0-9a-fA-F]{3,8})$/;

export const transformerShikiClasses = {
  name: "aliahmed:shiki-classes",
  span(node) {
    const match = typeof node.properties.style === "string" && node.properties.style.match(STYLE);
    if (!match) return;
    const [l, d] = [match[1].toLowerCase(), match[2].toLowerCase()];
    if (!known.sl.has(l) || !known.sd.has(d)) throw new Error(`shiki-colors.css has no class for ${l} / ${d}: rerun node scripts/shiki-classes.mjs`);
    delete node.properties.style;
    this.addClassToHast(node, [`sl-${l.slice(1)}`, `sd-${d.slice(1)}`]);
  },
};

if (import.meta.url === `file://${process.argv[1]}`) {
  const rules = Object.entries(known).flatMap(([prefix, colors]) =>
    [...colors].sort().map((c) => `.${prefix}-${c.slice(1)}{--shiki-${prefix === "sl" ? "light" : "dark"}:${c}}`)
  );
  writeFileSync(new URL("../src/styles/shiki-colors.css", import.meta.url), `/* Generated by scripts/shiki-classes.mjs. */\n${rules.join("\n")}\n`);
  console.log(`${rules.length} rules written`);
}
